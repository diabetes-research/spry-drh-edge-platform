class StateManager:
    """Manages Singer state bookmarks for resume-ability."""

    def __init__(self, state_path: Optional[str] = None):
        self.state = {}
        self.state_path = state_path
        if state_path and os.path.exists(state_path):
            try:
                with open(state_path, "r", encoding="utf-8") as f:
                    loaded = json.load(f)
                    self.state = (
                        loaded.get("bookmarks", {}) if isinstance(loaded, dict) else {}
                    )
            except Exception as e:
                LOGGER.warning(f"Failed to load state from {state_path}: {e}")

    def get_bookmark(self, stream: str, key: str) -> Optional[str]:
        """Retrieve bookmark value for a specific stream and key."""
        return self.state.get(stream, {}).get(key)

    def update_bookmark(self, stream: str, key: str, value: str):
        """Update bookmark value for a specific stream and key."""
        if stream not in self.state:
            self.state[stream] = {}
        self.state[stream][key] = value

    def emit_state(self):
        """Standard Singer STATE message."""
        print(json.dumps({"type": "STATE", "value": {"bookmarks": self.state}}))
        sys.stdout.flush()



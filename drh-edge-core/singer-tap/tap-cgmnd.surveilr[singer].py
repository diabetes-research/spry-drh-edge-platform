class ValidatingDRHLoader(DRHLoader):
    """
    Extension of DRHLoader that validates records against Key Properties and Schema Required fields.
    """

    def __init__(self, otel_resource_id=None):
        super().__init__()
        self.schemas = {}
        self.otel_resource_id = otel_resource_id
        self.trace_id = str(uuid.uuid4()).replace("-", "")

    def load_schema_if_needed(self, stream_name):
        """Ensure schema for stream is loaded in the validator."""
        if stream_name not in self.schemas:
            self.schemas[stream_name] = load_schema(stream_name)
        return self.schemas[stream_name]

    def emit_record(self, stream_name, record):
        """Validate record against schema and emit Singer RECORD message."""
        # Prevent recursion: Don't validate/log errors for OTel streams themselves
        if stream_name.startswith("otel_"):
            super().emit_record(stream_name, record)
            return

        # Ensure schema is loaded
        schema = self.load_schema_if_needed(stream_name)

        # 1. Check Key Properties (Primary Keys)
        key_props = STREAM_KEYS.get(stream_name, [])
        if key_props:
            missing_keys = [
                k for k in key_props if k not in record or record.get(k) is None
            ]
            # Filter out tenant fields from validation
            missing_keys = [
                k for k in missing_keys if k not in ("tenant_id", "tenant_name")
            ]

            if missing_keys:
                msg = f"Validation Error [Integrity]: Stream '{stream_name}' record missing KEY properties: {missing_keys}. Record skipped."
                LOGGER.error(msg)
                if self.otel_resource_id:
                    emit_otel_log(
                        self,
                        self.otel_resource_id,
                        "ERROR",
                        msg,
                        {"stream": stream_name, "error_type": "integrity"},
                    )
                return  # Skip emitting

        # 2. Check Required Fields (Mandatory Columns from Schema)
        if schema:
            required_fields = schema.get("required", [])
            if required_fields:
                missing_required = [
                    field for field in required_fields if field not in record
                ]
                # Filter out tenant fields
                missing_required = [
                    k for k in missing_required if k not in ("tenant_id", "tenant_name")
                ]

                if missing_required:
                    msg = f"Validation Error [Schema]: Stream '{stream_name}' record missing REQUIRED fields: {missing_required}. Record skipped."
                    LOGGER.error(msg)
                    if self.otel_resource_id:
                        emit_otel_log(
                            self,
                            self.otel_resource_id,
                            "ERROR",
                            msg,
                            {
                                "stream": stream_name,
                                "error_type": "schema",
                                "missing_fields": str(missing_required),
                            },
                        )
                    return  # Skip emitting

        # If validation passes, emit normally
        super().emit_record(stream_name, record)


class ForeignKeyValidator:
    """
    Validates Foreign Keys across all streams.
    Phase 1: Collection (during file reading)
    Phase 2: Global Validation (after all files read)
    """

    def __init__(self):
        # Maps stream_name -> set of collected IDs (Primary Keys)
        self.stream_ids = {}
        # List of pending checks: (source_stream, source_row_num, target_stream, target_id_value, field_name)
        self.pending_fks = []
        # Maps stream_name -> list of FK definitions from schema
        self.schema_refs = {}

    def register_schema(self, stream_name, schema):
        """Parse schema to identify Foreign Key relationships."""
        if stream_name in self.schema_refs:
            return

        self.schema_refs[stream_name] = []
        properties = schema.get("properties", {})

        for field_name, field_def in properties.items():
            # Support 1: Custom 'foreign_key' property
            fk_target = field_def.get("foreign_key")

            # Support 2: Standard JSON Schema '$ref'
            if not fk_target and "$ref" in field_def:
                ref = field_def["$ref"]
                match = re.match(r"^([a-zA-Z0-9_]+)\.json", ref)
                if match:
                    fk_target = match.group(1)

            if fk_target:
                self.schema_refs[stream_name].append(
                    {"field": field_name, "target_stream": fk_target}
                )

    def track_row(self, stream_name, row, filename, line_num):
        """
        1. Collect Primary Keys for this row.
        2. Record outgoing Foreign Keys for later validation.
        """
        # 1. Collect IDs
        pk_list = STREAM_KEYS.get(stream_name, [])

        for pk in pk_list:
            if pk in row and row[pk]:
                if stream_name not in self.stream_ids:
                    self.stream_ids[stream_name] = set()
                self.stream_ids[stream_name].add(row[pk])

        # 2. Track FKs
        if stream_name in self.schema_refs:
            for fk_def in self.schema_refs[stream_name]:
                field = fk_def["field"]
                target_stream = fk_def["target_stream"]

                val = row.get(field)
                if val:  # Only validate non-empty FKs
                    self.pending_fks.append(
                        {
                            "source_stream": stream_name,
                            "source_file": filename,
                            "line": line_num,
                            "field": field,
                            "value": val,
                            "target_stream": target_stream,
                        }
                    )

    def validate(self):
        """
        Global Validation Phase.
        Returns list of violation strings.
        """
        violations = []
        LOGGER.info(
            f"Starting Global FK Validation on {len(self.pending_fks)} references across {len(self.stream_ids)} streams..."
        )

        for check in self.pending_fks:
            target_stream = check["target_stream"]
            val = check["value"]

            if target_stream not in self.stream_ids:
                violations.append(
                    f"FK Violation in {check['source_file']} line {check['line']}: {check['field']}='{val}' refers to missing stream '{target_stream}'"
                )
                continue

            if val not in self.stream_ids[target_stream]:
                violations.append(
                    f"FK Violation in {check['source_file']} line {check['line']}: {check['field']}='{val}' not found in {target_stream}"
                )

        return violations



def normalize_timestamp(ts: str) -> str:
    """Normalize timestamp string to ISO 8601 format."""
    if not ts:
        return ""
    if "T" in ts:
        return ts
    # Handle "2018-01-01 12:00:00" -> ISO
    try:
        # Simple heuristic for common formats
        if " " in ts:
            dt = datetime.strptime(ts, "%Y-%m-%d %H:%M:%S")
            return dt.isoformat() + "Z"
        return ts
    except Exception:
        return ts


def process_cgm_tracing(
    emitter: ValidatingDRHLoader, data_dir: str, state: StateManager
):
    """
    Optimized: Efficiently streams CGM data using a single-pass approach per file.
    Groups metadata by file_name to avoid redundant I/O and uses O(1) matching.
    """
    meta_file = os.path.join(data_dir, "cgm_file_metadata.csv")
    if not os.path.exists(meta_file):
        LOGGER.info("No cgm_file_metadata.csv found, skipping CGM tracing.")
        return

    # 1. Load and Group Metadata by file_name
    files_to_patients = {}
    with open(meta_file, "r", encoding="utf-8-sig") as mf:
        meta_reader = csv.DictReader(mf)
        for row in meta_reader:
            fname = row.get("file_name", "").strip()
            if not fname:
                continue
            if not fname.lower().endswith(".csv"):
                fname += ".csv"

            fname = os.path.basename(fname)

            p_id = row.get("patient_id")
            if fname not in files_to_patients:
                files_to_patients[fname] = []

            row["_last_processed"] = state.get_bookmark("cgm_tracing", p_id)
            files_to_patients[fname].append(row)

    # 2. Process Files in a Single Pass
    start_time = get_time_nano()
    span_id, _ = emit_otel_span(
        emitter,
        emitter.otel_resource_id,
        OTelNames.CAT_CGM_INTEGRITY,
        start_time,
        start_time,
        trace_id=emitter.trace_id,
    )

    try:
        for fname, patient_list in files_to_patients.items():
            data_path = find_file(data_dir, fname)
            if not os.path.exists(data_path):
                LOGGER.warning(
                    f"Data file referenced in metadata not found: {data_path}"
                )
                continue

            LOGGER.info(
                f"Scanning {fname} (Single-pass for {len(patient_list)} patients)..."
            )

            # Build O(1) fast lookup map for this file
            # pid_col -> {raw_csv_value -> p_meta}
            fast_lookup = {}
            max_ts_map = {}

            for p_meta in patient_list:
                p_id = p_meta.get("patient_id")
                study_id = p_meta.get("study_id", "")
                pid_col = p_meta.get("map_field_of_patient_id", "PtID")

                bucket = fast_lookup.setdefault(pid_col, {})
                # Direct match
                bucket[p_id] = p_meta
                # Strip study-id prefix if present
                if study_id and p_id.startswith(f"{study_id}-"):
                    raw_stripped = p_id[len(study_id) + 1 :]
                    bucket[raw_stripped] = p_meta

                max_ts_map[p_id] = p_meta["_last_processed"]

            with open(data_path, "r", encoding="utf-8-sig") as df:
                reader = csv.DictReader(df)
                chunk_count = 0

                for d_row in reader:
                    # O(1) Routing
                    for pid_col, bucket in fast_lookup.items():
                        raw_val = d_row.get(pid_col)
                        if not raw_val:
                            continue

                        p_meta = bucket.get(raw_val)
                        if not p_meta:
                            continue

                        # Match Found!
                        p_id = p_meta.get("patient_id")
                        study_id = p_meta.get("study_id")
                        col_date = p_meta.get("map_field_of_cgm_date")
                        col_val = p_meta.get("map_field_of_cgm_value")
                        last_ts = p_meta["_last_processed"]
                        tenant_id = os.environ.get(
                            "TENANT_ID", p_meta.get("tenant_id", "")
                        )

                        raw_ts = d_row.get(col_date)
                        ts = normalize_timestamp(raw_ts)

                        if not ts or (last_ts and ts <= last_ts):
                            continue

                        val = d_row.get(col_val)
                        if not val:
                            continue

                        record = {
                            "tenant_id": tenant_id,
                            "study_id": study_id,
                            "participant_id": p_id,
                            "Date_Time": ts,
                            "CGM_Value": float(val),
                        }
                        emitter.emit_record("combined_cgm_tracing", record)

                        if not max_ts_map[p_id] or ts > max_ts_map[p_id]:
                            max_ts_map[p_id] = ts

                        chunk_count += 1
                        if chunk_count % 100000 == 0:
                            for pid, m_ts in max_ts_map.items():
                                if m_ts:
                                    state.update_bookmark("cgm_tracing", pid, m_ts)
                            state.emit_state()

            for pid, m_ts in max_ts_map.items():
                if m_ts:
                    state.update_bookmark("cgm_tracing", pid, m_ts)

        emit_otel_span(
            emitter,
            emitter.otel_resource_id,
            OTelNames.CAT_CGM_INTEGRITY,
            start_time,
            get_time_nano(),
            span_id=span_id,
            trace_id=emitter.trace_id,
            status_code="OK",
        )

    except Exception as e:
        LOGGER.error(f"Critical error in CGM streaming: {e}")
        emit_otel_span(
            emitter,
            emitter.otel_resource_id,
            OTelNames.CAT_CGM_INTEGRITY,
            start_time,
            get_time_nano(),
            span_id=span_id,
            trace_id=emitter.trace_id,
            status_code="ERROR",
        )


